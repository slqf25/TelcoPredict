def transform_customer_profile(
    gender, senior_citizen, partner, dependents, tenure, contract,
    paperless_billing, payment_method, monthly_charges, total_charges,
    phone_service, multiple_lines, internet_service, addon_vals,
    feature_columns, scaler,
):
    """Apply the deployed one-row preprocessing path without fitting anything."""
    effective_addons = dict(addon_vals)
    effective_lines = multiple_lines
    if internet_service == "No":
        effective_addons = {service: "No" for service in ADDON_SERVICES}
    if phone_service == "No":
        effective_lines = "No"

    raw_input = pd.DataFrame([{
        "customerID": "PROTOTYPE-INPUT", "gender": gender,
        "SeniorCitizen": 1 if senior_citizen == "Yes" else 0,
        "Partner": partner, "Dependents": dependents, "tenure": tenure,
        "PhoneService": phone_service, "MultipleLines": effective_lines,
        "InternetService": internet_service,
        "OnlineSecurity": effective_addons["OnlineSecurity"],
        "OnlineBackup": effective_addons["OnlineBackup"],
        "DeviceProtection": effective_addons["DeviceProtection"],
        "TechSupport": effective_addons["TechSupport"],
        "StreamingTV": effective_addons["StreamingTV"],
        "StreamingMovies": effective_addons["StreamingMovies"],
        "Contract": contract, "PaperlessBilling": paperless_billing,
        "PaymentMethod": payment_method, "MonthlyCharges": monthly_charges,
        "TotalCharges": total_charges, "Churn": "No",
    }])
    cleaned = engineer_and_clean(raw_input)
    model_input = build_feature_matrix_proto(cleaned).reindex(
        columns=feature_columns, fill_value=0
    )
    scaled_input = model_input.copy()
    scaled_input[NUM_COLS_TO_SCALE] = scaler.transform(model_input[NUM_COLS_TO_SCALE])
    return model_input, scaled_input

